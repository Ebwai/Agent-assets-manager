import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {validateRule,renderRule,parseRule} from '../rules.mjs';

const rule=()=>({title:'接口规范',description:'接口输入必须验证',harness:'claude',fileName:'接口规范.md',paths:['src/api/**/*.ts'],content:'# 接口规范\n\n- 校验所有输入。'});

test('Claude Rules 导入和输出保持 paths；拒绝无效 YAML 与文件路径',()=>{
  const asset=rule();
  assert.deepEqual(parseRule(renderRule(asset),asset.fileName).asset.paths,asset.paths);
  assert.equal(parseRule('---\npaths: "src/**, tests/**"\npriority: high\n---\n规则正文','test.md').ignoredFields[0],'priority');
  assert.deepEqual(parseRule('项目规范','test.md').asset.paths,[]);
  assert.deepEqual(parseRule('---\n---\n项目规范','test.md').asset.paths,[]);
  assert.deepEqual(parseRule('---\npaths: "src/**/*.{ts,tsx}, tests/**"\n---\n项目规范','test.md').asset.paths,['src/**/*.{ts,tsx}','tests/**']);
  assert.throws(()=>parseRule('---\npaths: [\n---\n正文','test.md'),/YAML/);
  assert.throws(()=>validateRule({...asset,fileName:'../outside.md'}),/文件名/);
  assert.throws(()=>validateRule({...asset,paths:['../outside/**']}),/相对 glob/);
  assert.throws(()=>validateRule({...asset,harness:'codex'}),/仅支持/);
  assert.throws(()=>validateRule({...asset,content:'---\npaths: [foo]\n---\ntext'}),/正文不应/);
});

test('Rules 版本、项目和 Agent 关联、生效移除，以及项目实际资产视图',async t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'asset-rules-test-'));
  const directory=path.join(temp,'project');fs.mkdirSync(directory);
  const port=45000+Math.floor(Math.random()*10000);
  const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,ASSET_DATA_DIR:path.join(temp,'data'),PORT:String(port)},stdio:'pipe'});
  t.after(()=>{server.kill();fs.rmSync(temp,{recursive:true,force:true});});
  const request=async(url,method='GET',body)=>{const res=await fetch(`http://127.0.0.1:${port}/api/${url}`,{method,headers:{'content-type':'application/json'},body:body?JSON.stringify(body):undefined});const result=await res.json();if(!res.ok)throw Error(result.error);return result;};
  let ready=false;for(let i=0;i<80;i++){try{await request('bootstrap');ready=true;break;}catch{await new Promise(r=>setTimeout(r,100));}}assert.ok(ready);
  const asset=await request('rule','POST',{asset:rule(),message:'添加接口规范'});
  const project=await request('project','POST',{asset:{title:'规则项目',directory,ruleIds:[asset.id]},message:'关联默认规则'});
  const outside=path.join(directory,'.claude','rules','existing.md');fs.mkdirSync(path.dirname(outside),{recursive:true});fs.writeFileSync(outside,'人工已有规范');
  const instructions=path.join(directory,'CLAUDE.md');fs.writeFileSync(instructions,'已有项目指令');
  const body={projectId:project.id,software:'claude',promptIds:[]};
  const preview=await request('deploy','POST',{...body,preview:true});
  const managed=preview.files.find(file=>file.path.endsWith(asset.fileName));assert.ok(managed);
  assert.equal(fs.existsSync(managed.path),false,'preview does not write files');
  assert.equal(preview.files.some(file=>file.path===instructions),false,'rule-only application does not rewrite prompt files');
  await request('deploy','POST',body);await request('deploy','POST',body);
  let view=await request(`project-configuration?projectId=${project.id}`);
  const claude=view.deployments.find(d=>d.software==='claude');
  assert.equal(claude.assets.filter(a=>a.type==='rule').length,1);
  assert.equal(claude.assets[0].title,asset.title);assert.ok(claude.assets[0].version);
  assert.ok(claude.files.every(file=>file.status==='unchanged'));
  assert.equal(view.externalRules[0].path,'.claude/rules/existing.md');
  assert.equal(fs.readFileSync(instructions,'utf8'),'已有项目指令');
  const updated=await request('rule','POST',{asset:{...asset,content:'更新后的接口规范'},message:'更新接口规范'});
  view=await request(`project-configuration?projectId=${project.id}`);
  assert.equal(view.deployments[0].assets[0].hasNewVersion,true);
  const versions=await request(`rule/${asset.id}/history`);assert.equal(versions.length,2);
  await request(`rule/${asset.id}/select-version`,'POST',{hash:versions[1].hash});
  await request('deploy','POST',body);assert.equal(fs.readFileSync(managed.path,'utf8'),renderRule(asset));
  await request(`rule/${asset.id}/select-version`,'POST',{});
  fs.writeFileSync(managed.path,'手动修改');
  await assert.rejects(request('deploy','POST',body),/Rule 已在项目中修改/);
  view=await request(`project-configuration?projectId=${project.id}`);
  assert.equal(view.deployments[0].files.find(f=>f.path.endsWith(asset.fileName)).status,'modified');
  fs.writeFileSync(managed.path,renderRule(asset));
  await request('deploy','POST',{...body,ruleIds:[]});
  assert.equal(fs.existsSync(managed.path),false);assert.equal(fs.readFileSync(outside,'utf8'),'人工已有规范');
  assert.equal((await request(`deployment-hooks?projectId=${project.id}&software=claude`)).rulesApplied,false);
  await assert.rejects(request('deploy','POST',{...body,software:'codex',ruleIds:[asset.id]}),/Rules 仅支持/);
  const model=await request('model','POST',{asset:{title:'测试模型',model:'test',baseUrl:'https://api.anthropic.com'},message:'登记测试模型'});
  const hook=await request('hook','POST',{asset:{title:'记录事件',harness:'claude',event:'Stop',matcher:'',async:false,timeout:3,runtime:'node',entry:'scripts/main.mjs',files:{'scripts/main.mjs':'process.exit(0);'}},message:'登记关联 Hook'});
  const prompt=await request('prompt','POST',{asset:{title:'项目提示',assetHarness:'claude',assetModelId:model.id,scope:'global',content:'保持清晰沟通'},message:'登记项目提示'});
  const agent=await request('agent','POST',{asset:{title:'接口 Agent',assetHarness:'claude',assetModelId:model.id,harness:'claude',modelId:model.id,ruleIds:[asset.id],hookIds:[hook.id],skillIds:[],workflowIds:[],promptIds:[prompt.id],instructions:'检查接口',tools:['Read'],mcps:[{name:'test-mcp',command:'node',args:['server.js'],env:{SECRET:'never-return'}}]},message:'Agent 关联规范'});
  await request('deploy','POST',{...body,agentId:agent.id,modelId:model.id,ruleIds:[asset.id],promptIds:[prompt.id]});
  view=await request(`project-configuration?projectId=${project.id}`);
  assert.equal(view.deployments[0].assets.filter(a=>a.type==='rule').length,1,'Agent and direct selection deduplicate');
  for(const type of ['agent','hook','prompt','rule'])assert.ok(view.deployments[0].assets.some(a=>a.type===type));
  assert.equal(view.deployments[0].modelTitle,'测试模型');assert.deepEqual(view.deployments[0].tools,['Read']);assert.deepEqual(view.deployments[0].mcps,['test-mcp']);
  assert.ok(!JSON.stringify(view).includes('never-return'),'configuration view never returns MCP secret values');
  fs.unlinkSync(managed.path);
  view=await request(`project-configuration?projectId=${project.id}`);
  assert.equal(view.deployments[0].files.find(f=>f.path.endsWith(asset.fileName)).status,'missing');
  await request('rule/'+asset.id,'DELETE',{message:'删除测试规则'});
  view=await request(`project-configuration?projectId=${project.id}`);assert.equal(view.deployments[0].assets.find(a=>a.type==='rule').deleted,true);
  await request(`rule/${asset.id}/restore`,'POST',{hash:versions[0].hash,message:'恢复规则资产'});
  assert.equal((await request('rule/'+asset.id)).content,updated.content);
  // Old deployments keep unknown versions unknown, rather than inventing them.
  fs.writeFileSync(path.join(directory,'.agent-asset-manager','codex.json'),JSON.stringify({files:[],skillIds:[],promptIds:[],updatedAt:new Date().toISOString()}));
  view=await request(`project-configuration?projectId=${project.id}`);assert.equal(view.deployments[1].legacy,true);
});
