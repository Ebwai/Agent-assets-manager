import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {spawn} from 'node:child_process';

test('Hooks 组版本、同软件成员检查、整组生效、跨来源去重与撤销',async t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'asset-hookgroups-'));
  const port=46000+Math.floor(Math.random()*10000);
  const server=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:String(port),ASSET_DATA_DIR:path.join(temp,'data')},stdio:'pipe'});
  t.after(()=>{server.kill();fs.rmSync(temp,{recursive:true,force:true});});
  const request=async(url,method='GET',body)=>{const res=await fetch(`http://127.0.0.1:${port}/api/${url}`,{method,headers:{'content-type':'application/json'},body:body?JSON.stringify(body):undefined});const result=await res.json();if(!res.ok)throw Error(result.error);return result;};
  let ready=false;for(let i=0;i<100;i++){try{await request('bootstrap');ready=true;break;}catch{await new Promise(r=>setTimeout(r,100));}}assert.ok(ready);
  const create=(type,asset,message='保存测试资产')=>request(type,'POST',{asset,message});
  const makeHook=(harness,title,event)=>({harness,title,event,matcher:event==='PreToolUse'?'Bash':'',async:false,timeout:5,runtime:'node',entry:'scripts/main.mjs',files:{'scripts/main.mjs':'process.exit(0);'}});
  const foreign=await create('hook',makeHook('codex','其他软件 Hook','Stop'));
  for(const harness of ['claude','codex']) {
    const h1=await create('hook',makeHook(harness,'编辑前检查','PreToolUse'));
    const h2=await create('hook',makeHook(harness,'结束检查','Stop'));
    const base={title:`${harness} 质量检查`,description:'编辑前检查危险操作，结束前检查交付结果',harness,members:[{hookId:h1.id,role:'保护文件'},{hookId:h2.id,role:'检查交付'}]};
    await assert.rejects(create('hookgroup',{...base,description:''}),/共同用途/);
    await assert.rejects(create('hookgroup',{...base,members:[]}),/成员/);
    await assert.rejects(create('hookgroup',{...base,members:[{hookId:h1.id},{hookId:h1.id}]}),/重复/);
    if(harness==='claude')await assert.rejects(create('hookgroup',{...base,members:[{hookId:foreign.id}]}),/此软件/);
    const group=await create('hookgroup',base);
    const shared=await create('hookgroup',{title:'文件保护',description:'保护项目文件',harness,members:[{hookId:h1.id}]});
    const agent=await create('agent',{title:'检查助手',harness,hookIds:[h2.id],hookGroupIds:[group.id],skillIds:[],workflowIds:[],promptIds:[],tools:[],mcps:[]});
    const directory=path.join(temp,harness);fs.mkdirSync(directory);
    const project=await create('project',{title:harness,directory});
    const body={projectId:project.id,software:harness,agentId:agent.id,hookIds:[h1.id],hookGroupIds:[group.id,shared.id],suiteIds:[],promptIds:[]};
    const preview=await request('deploy','POST',{...body,preview:true});
    const scripts=preview.files.filter(f=>f.path.endsWith(path.join('scripts','main.mjs')));assert.equal(scripts.length,2);
    assert.ok(scripts.every(f=>!fs.existsSync(f.path)),'preview does not deploy');
    await request('deploy','POST',body);await request('deploy','POST',body);
    let manifest=JSON.parse(fs.readFileSync(path.join(directory,'.agent-asset-manager',`${harness}.json`),'utf8'));
    assert.equal(manifest.hookIds.length,2);assert.equal(manifest.hookGroupIds.length,2);assert.deepEqual(manifest.directHookIds,[h1.id]);
    const status=await request(`deployment-hooks?projectId=${project.id}&software=${harness}`);
    assert.deepEqual(status.hookIds,[h1.id]);assert.equal(status.hookGroupIds.length,2,'restoring selection must not turn group members into direct selections');
    const view=await request(`project-configuration?projectId=${project.id}`);
    const deployed=view.deployments.find(d=>d.software===harness);
    assert.equal(deployed.assets.filter(a=>a.type==='hookgroup').length,2);assert.equal(deployed.assets.filter(a=>a.type==='hook').length,2);
    await create('hookgroup',{...group,members:[{hookId:h1.id,role:'保护文件'}]},'更新组内成员');
    const solo={projectId:project.id,software:harness,hookIds:[],hookGroupIds:[group.id,shared.id],suiteIds:[],promptIds:[]};
    await request('deploy','POST',solo);
    manifest=JSON.parse(fs.readFileSync(path.join(directory,'.agent-asset-manager',`${harness}.json`),'utf8'));
    assert.deepEqual(manifest.hookIds,[h1.id]);assert.equal(fs.existsSync(scripts.find(f=>f.path.includes(h2.id)).path),false);
    const history=await request(`hookgroup/${group.id}/history`);assert.equal(history.length,2);
    await request(`hookgroup/${group.id}/select-version`,'POST',{hash:history[1].hash});
    await request('deploy','POST',solo);assert.ok(fs.existsSync(scripts.find(f=>f.path.includes(h2.id)).path));
    await request(`hookgroup/${group.id}/select-version`,'POST',{});
    await request('deploy','POST',{...solo,hookGroupIds:[]});
    assert.equal((await request(`deployment-hooks?projectId=${project.id}&software=${harness}`)).applied,false);
    assert.ok(scripts.every(f=>!fs.existsSync(f.path)));
    await request(`hook/${h1.id}`,'DELETE',{message:'删除组内成员'});
    await assert.rejects(request('deploy','POST',{...solo,preview:true}),/已删除/);
    const versions=await request(`hook/${h1.id}/history`);
    await request(`hook/${h1.id}/restore`,'POST',{hash:versions.at(-1).hash,message:'恢复组内成员'});
    await request(`hookgroup/${group.id}`,'DELETE',{message:'删除测试组'});
    await request(`hookgroup/${group.id}/restore`,'POST',{hash:history[0].hash,message:'恢复测试组'});
    assert.equal((await request(`hookgroup/${group.id}`)).members.length,1);
  }
});
