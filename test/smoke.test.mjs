import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';

test('资产保存、Git 历史、回滚与双软件生效', async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-assets-test-'));
  const projectDir = path.join(temp, 'project');
  fs.mkdirSync(projectDir);
  const port = 40000 + Math.floor(Math.random() * 15000);
  const server = spawn(process.execPath, ['server.mjs'], { cwd: path.resolve('.'), env: { ...process.env, ASSET_DATA_DIR: path.join(temp, 'data'), PORT: String(port) }, stdio: 'pipe' });
  t.after(() => { server.kill(); fs.rmSync(temp, { recursive: true, force: true }); });
  const request = async (url, method = 'GET', body) => {
    const res = await fetch(`http://127.0.0.1:${port}/api/${url}`, { method, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
    const result = await res.json();
    if (!res.ok) throw new Error(result.error);
    return result;
  };
  let ready = false;
  for (let i = 0; i < 100; i++) {
    try { await request('bootstrap'); ready = true; break; } catch { await new Promise(r => setTimeout(r, 100)); }
  }
  assert.ok(ready, 'server started');
  const imported = await request('import-skill', 'POST', { skillMd: `---\nname: sample-skill\ndescription: >-\n  Read project files when the user asks for an audit.\nmetadata:\n  version: 2.0.0\nallowed-tools:\n  - Read\n  - Grep\n---\n# Sample Skill\n\nFollow these steps.\n` });
  assert.equal(imported.frontmatter.name, 'sample-skill');
  assert.equal(imported.frontmatter.description, 'Read project files when the user asks for an audit.');
  assert.deepEqual(imported.frontmatter['allowed-tools'], ['Read', 'Grep']);
  assert.match(imported.body, /Follow these steps/);
  await assert.rejects(request('import-skill', 'POST', { skillMd: '---\nname: broken\nname: repeated\n---\nBody' }), /YAML 解析失败/);
  await assert.rejects(request('import-skill', 'POST', { skillMd: '---\nname: no-end\nBody' }), /结束标记/);
  await assert.rejects(request('skill', 'POST', { message: '', asset: { title: '无效' } }), /版本说明/);
  const skill = await request('skill', 'POST', { message: '创建测试能力', asset: { title: '文件检查', description: '检查文件', variants: { common: { frontmatter: { name: 'file-check', description: '检查文件。用户要求检查文件时使用。', metadata: { version: '1.0.0' }, 'allowed-tools': 'Read Grep' }, body: '## Core workflow\n\n1. Read the file.\n\n## Verification\n\nReport result.' } }, files: { 'scripts/check.js': 'console.log("ok")', 'references/rules.md': 'Check names.', 'assets/data.bin': { encoding: 'base64', data: Buffer.from([0,1,2,255]).toString('base64'), mime: 'application/octet-stream' } } } });
  assert.equal((await request(`skill/${skill.id}/history`)).length, 1);
  assert.ok((await request('recent')).some(item => item.type === 'skill' && item.id === skill.id && item.message.includes('创建测试能力')));
  skill.variants.common.body = '## Core workflow\n\n1. Read the file carefully.\n\n## Verification\n\nReport result.';
  await request('skill', 'POST', { message: '完善检查步骤', asset: skill });
  const versions = await request(`skill/${skill.id}/history`);
  assert.equal(versions.length, 2);
  assert.match((await request(`skill/${skill.id}/diff?hash=${versions[0].hash}`)).diff, /carefully/);
  await request(`skill/${skill.id}/restore`, 'POST', { hash: versions[1].hash, message: '恢复初始版本' });
  assert.equal((await request(`skill/${skill.id}`)).variants.common.body.includes('carefully'), false);
  const project = await request('project', 'POST', { message: '登记测试项目', asset: { title: '测试项目', directory: projectDir } });
  await assert.rejects(request('workflow', 'POST', { message: '创建无效套件', asset: { title: '无效套件', description: '检查文件', members: [{ skillId: skill.id, role: '' }] } }), /定位和作用/);
  const workflow = await request('workflow', 'POST', { message: '创建测试套件', asset: { title: '文件处理套件', description: '集中处理项目中的文件检查任务', members: [{ skillId: skill.id, role: '读取文件并检查内容是否符合规则' }] } });
  const agent = await request('agent', 'POST', { message: '创建测试 Agent', asset: { title: '检查助手', skillIds: [skill.id], workflowIds: [workflow.id], promptIds: [], tools: ['Read'], mcps: [{ name: 'demo', command: 'node', args: ['demo.js'] }] } });
  const codexAgent = await request('agent', 'POST', { message: '创建 Codex Agent', asset: { title: 'Codex 检查助手', harness: 'codex', skillIds: [skill.id], workflowIds: [], promptIds: [], tools: ['shell', 'apply_patch'], mcps: [] } });
  await assert.rejects(request('deploy', 'POST', { projectId: project.id, agentId: codexAgent.id, software: 'claude', preview: true }), /适用于 Codex/);
  const codexPreview = await request('deploy', 'POST', { projectId: project.id, agentId: codexAgent.id, software: 'codex', preview: true });
  assert.ok(codexPreview.files.some(file => file.path.endsWith('AGENTS.md') && file.content.includes('shell')));
  const suiteProjectDir = path.join(temp, 'suite-project');
  fs.mkdirSync(suiteProjectDir);
  const suiteProject = await request('project', 'POST', { message: '登记套件项目', asset: { title: '套件项目', directory: suiteProjectDir, suiteIds: [workflow.id] } });
  const suitePreview = await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex', preview: true });
  assert.ok(suitePreview.files.some(file => file.path.endsWith('AGENTS.md') && file.content.includes('读取文件并检查内容是否符合规则')));
  await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex' });
  assert.ok(fs.existsSync(path.join(suiteProjectDir, '.agents/skills/file-check/SKILL.md')));
  assert.equal(fs.existsSync(path.join(suiteProjectDir, '.agents/skills/check-flow/SKILL.md')), false);
  const model = await request('model', 'POST', { message: '登记目标模型', asset: { title: '测试模型', model: 'test-model', baseUrl: 'https://api.anthropic.com' } });
  await request('prompt', 'POST', { message: '创建通用提示词', asset: { title: '通用规则', scope: 'global', content: 'GLOBAL_RULE' } });
  const projectPrompt = await request('prompt', 'POST', { message: '创建项目提示词', asset: { title: '项目规则', scope: 'project', target: suiteProject.id, content: 'PROJECT_RULE' } });
  const modelPrompt = await request('prompt', 'POST', { message: '创建模型提示词', asset: { title: '模型规则', scope: 'model', target: model.id, content: 'MODEL_RULE' } });
  const harnessPrompt = await request('prompt', 'POST', { message: '创建 Harness 提示词', asset: { title: 'Codex 规则', scope: 'software', target: 'codex', content: 'HARNESS_RULE' } });
  const combined = await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex', modelId: model.id, skillIds: [skill.id], suiteIds: [workflow.id], promptIds: [projectPrompt.id, modelPrompt.id, harnessPrompt.id], preview: true });
  assert.equal(combined.files.filter(file => file.path.endsWith(path.join('file-check', 'SKILL.md'))).length, 1);
  const promptDocument = combined.files.find(file => file.path.endsWith('codex-system-prompt.md'));
  assert.ok(promptDocument);
  assert.ok(promptDocument.content.indexOf('MODEL_RULE') < promptDocument.content.indexOf('HARNESS_RULE'));
  assert.ok(promptDocument.content.indexOf('HARNESS_RULE') < promptDocument.content.indexOf('PROJECT_RULE'));
  assert.doesNotMatch(promptDocument.content, /GLOBAL_RULE/);
  assert.ok(combined.files.some(file => file.path.endsWith('AGENTS.md') && file.content.includes('PROJECT_RULE')));
  await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex', modelId: model.id, skillIds: [skill.id], suiteIds: [workflow.id], promptIds: [projectPrompt.id, modelPrompt.id, harnessPrompt.id] });
  assert.match(fs.readFileSync(path.join(suiteProjectDir, '.agent-asset-manager/codex-system-prompt.md'), 'utf8'), /PROJECT_RULE/);
  const singleOnly = await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex', skillIds: [skill.id], suiteIds: [], promptIds: [], preview: true });
  assert.equal(singleOnly.files.filter(file => file.path.endsWith(path.join('file-check', 'SKILL.md'))).length, 1);
  assert.equal(singleOnly.files.some(file => file.path.endsWith('codex-system-prompt.md')), false);
  const promptOnly = await request('deploy', 'POST', { projectId: suiteProject.id, software: 'codex', skillIds: [], suiteIds: [], promptIds: [projectPrompt.id], preview: true });
  assert.ok(promptOnly.files.some(file => file.path.endsWith('codex-system-prompt.md')));
  await assert.rejects(request('compose', 'POST', { projectId: suiteProject.id, software: 'claude', promptIds: [harnessPrompt.id] }), /不匹配/);
  for (const software of ['claude', 'codex']) {
    const plan = await request('deploy', 'POST', { projectId: project.id, agentId: agent.id, software, preview: true });
    assert.ok(plan.files.length >= 4);
    await request('deploy', 'POST', { projectId: project.id, agentId: agent.id, software });
  }
  assert.ok(fs.existsSync(path.join(projectDir, '.claude/skills/file-check/SKILL.md')));
  assert.ok(fs.existsSync(path.join(projectDir, '.agents/skills/file-check/SKILL.md')));
  assert.equal(fs.readFileSync(path.join(projectDir, '.agents/skills/file-check/scripts/check.js'), 'utf8'), 'console.log("ok")');
  assert.match(fs.readFileSync(path.join(projectDir, '.claude/skills/file-check/SKILL.md'), 'utf8'), /allowed-tools: "Read Grep"/);
  assert.doesNotMatch(fs.readFileSync(path.join(projectDir, '.agents/skills/file-check/SKILL.md'), 'utf8'), /allowed-tools/);
  assert.deepEqual(fs.readFileSync(path.join(projectDir, '.agents/skills/file-check/assets/data.bin')), Buffer.from([0,1,2,255]));
  assert.match(fs.readFileSync(path.join(projectDir, '.codex/config.toml'), 'utf8'), /^# Agent Asset Manager: start/m);
  assert.match(fs.readFileSync(path.join(projectDir, 'CLAUDE.md'), 'utf8'), /检查助手/);
  agent.skillIds = [];
  agent.workflowIds = [];
  agent.tools = [];
  agent.mcps = [];
  await request('agent', 'POST', { message: '移除旧能力配置', asset: agent });
  await request('deploy', 'POST', { projectId: project.id, agentId: agent.id, software: 'claude' });
  assert.equal(fs.existsSync(path.join(projectDir, '.claude/skills/file-check/SKILL.md')), false);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(projectDir, '.claude/settings.json'), 'utf8')).permissions.allow, []);
  const prompt = await request('prompt', 'POST', { message: '创建临时提示词', asset: { title: '临时规则', scope: 'global', content: 'Be concise.' } });
  await request(`prompt/${prompt.id}`, 'DELETE', { message: '删除临时提示词' });
  const deleted = await request('trash?type=prompt');
  assert.equal(deleted.length, 1);
  await request(`prompt/${prompt.id}/restore`, 'POST', { hash: deleted[0].hash, message: '恢复临时提示词' });
  assert.equal((await request(`prompt/${prompt.id}`)).title, '临时规则');
});
