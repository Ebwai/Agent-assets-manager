import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';

test('增量生效保留未操作版本，显式移除与预览保护', async t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'asset-incremental-'));
  const directory=path.join(temp,'project');fs.mkdirSync(directory);
  const port=40000+Math.floor(Math.random()*15000);
  const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,ASSET_DATA_DIR:path.join(temp,'data'),PORT:String(port)},stdio:'pipe'});
  t.after(()=>{child.kill();fs.rmSync(temp,{recursive:true,force:true});});
  const api=async(url,method='GET',body)=>{
    const res=await fetch(`http://127.0.0.1:${port}/api/${url}`,{method,headers:{'content-type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
    const result=await res.json();if(!res.ok)throw Error(result.error);return result;
  };
  let ready=false;for(let i=0;i<100;i++){try{await api('bootstrap');ready=true;break;}catch{await new Promise(r=>setTimeout(r,100));}}assert.ok(ready);
  const project=await api('project','POST',{message:'登记项目',asset:{title:'增量项目',directory}});
  const model=await api('model','POST',{message:'创建模型',asset:{title:'模型',model:'test',baseUrl:'https://example.com'}});
  const create=async(name)=>api('skill','POST',{message:`创建 ${name}`,asset:{title:name,variants:{common:{frontmatter:{name,description:'用于验证资产应用'},body:name+' v1'}},files:{}}});
  let a=await create('alpha'),b=await create('bravo'),c=await create('charlie');
  const suite=await api('workflow','POST',{message:'创建套件',asset:{title:'套件',description:'验证',members:[{skillId:a.id,role:'A'},{skillId:b.id,role:'B'}]}});
  const base={projectId:project.id,software:'codex',modelId:model.id,incremental:true};
  const apply=async(change)=>{const body={...base,...change};const plan=await api('deploy','POST',{...body,preview:true});await api('deploy','POST',{...body,previewToken:plan.previewToken});return plan;};
  const file=name=>path.join(directory,'.agents','skills',name,'SKILL.md');
  const status=async()=> (await api('project-configuration?projectId='+project.id)).deployments.find(d=>d.software==='codex');
  await apply({suiteIds:[suite.id],skillIds:[c.id]});
  const oldB=fs.readFileSync(file('bravo'),'utf8');
  a.variants.common.body='alpha v2';a=await api('skill','POST',{message:'A 更新',asset:a});
  b.variants.common.body='bravo v2';b=await api('skill','POST',{message:'B 更新',asset:b});
  assert.equal((await status()).assets.find(ref=>ref.id===a.id).hasNewVersion,true);
  const before=fs.readFileSync(file('alpha'),'utf8');
  const preview=await api('deploy','POST',{...base,skillIds:[a.id],preview:true});
  assert.equal(fs.readFileSync(file('alpha'),'utf8'),before);
  assert.equal(preview.removals.length,0);
  await apply({skillIds:[a.id]});
  assert.match(fs.readFileSync(file('alpha'),'utf8'),/alpha v2/);
  assert.equal(fs.readFileSync(file('bravo'),'utf8'),oldB);
  assert.ok(fs.existsSync(file('charlie')));
  assert.equal((await status()).assets.find(ref=>ref.id===b.id).hasNewVersion,true);
  await apply({removeAssets:[{type:'skill',id:a.id}]});
  assert.equal(fs.existsSync(file('alpha')),false);
  assert.ok((await status()).assets.some(ref=>ref.id===suite.id));
  assert.ok(!(await status()).assets.some(ref=>ref.id===a.id));
  await apply({skillIds:[c.id]});assert.equal(fs.existsSync(file('alpha')),false);
  await apply({skillIds:[a.id]});assert.ok(fs.existsSync(file('alpha')));
  await apply({removeAssets:[{type:'workflow',id:suite.id}]});
  assert.ok(fs.existsSync(file('alpha')),'独立引用的成员保留');
  assert.equal(fs.existsSync(file('bravo')),false,'套件独占成员移除');
  const stale=await api('deploy','POST',{...base,skillIds:[c.id],preview:true});
  fs.appendFileSync(file('charlie'),'\nexternal change');
  await assert.rejects(api('deploy','POST',{...base,skillIds:[c.id],previewToken:stale.previewToken}),/重新预览/);
  await apply({removeAssets:[{type:'skill',id:a.id},{type:'skill',id:c.id}]});
  assert.equal((await status()).assets.length,0);
  assert.equal(fs.existsSync(file('alpha')),false);
  assert.equal(fs.existsSync(file('charlie')),false);
  // 旧版 manifest 用记录的 Git 版本恢复未操作资产。
  await api('deploy','POST',{projectId:project.id,software:'codex',suiteIds:[suite.id],modelId:model.id});
  const manifestPath=path.join(directory,'.agent-asset-manager','codex.json');
  const manifest=JSON.parse(fs.readFileSync(manifestPath));delete manifest.assetContents;delete manifest.roots;
  fs.writeFileSync(manifestPath,JSON.stringify(manifest));
  await apply({skillIds:[c.id]});assert.match(fs.readFileSync(file('bravo'),'utf8'),/bravo v2/);
  // 另一框架使用独立应用记录，不会清理 Codex 的文件。
  await apply({software:'claude',skillIds:[a.id]});assert.ok(fs.existsSync(file('bravo')));
  const prompt=await api('prompt','POST',{message:'创建提示词',asset:{title:'Agent 提示词',scope:'global',content:'AGENT_PROMPT_V1'}});
  const hook=await api('hook','POST',{message:'创建自动检查',asset:{title:'自动检查',harness:'codex',event:'PreToolUse',matcher:'Bash',async:false,timeout:3,runtime:'node',entry:'scripts/main.mjs',files:{'scripts/main.mjs':'console.log("hook-v1");'}}});
  const group=await api('hookgroup','POST',{message:'创建检查分组',asset:{title:'检查分组',description:'检查项目',harness:'codex',members:[{hookId:hook.id,role:'检查命令'}]}});
  const agent=await api('agent','POST',{message:'创建应用助手',asset:{title:'应用助手',harness:'codex',instructions:'保留项目上下文',skillIds:[],workflowIds:[],promptIds:[prompt.id],hookIds:[],hookGroupIds:[group.id],tools:[],mcps:[]}});
  await apply({agentId:agent.id});
  assert.match(fs.readFileSync(path.join(directory,'AGENTS.md'),'utf8'),/AGENT_PROMPT_V1/);
  const hookPath=path.join(directory,'.codex','hooks','asset-manager',hook.id,'scripts','main.mjs');
  const originalHook=fs.readFileSync(hookPath,'utf8');
  await api('hook','POST',{message:'更新自动检查',asset:{...hook,files:{'scripts/main.mjs':'console.log("hook-v2");'}}});
  await api('prompt','POST',{message:'更新提示内容',asset:{...prompt,content:'AGENT_PROMPT_V2'}});
  await apply({skillIds:[c.id]});
  assert.equal(fs.readFileSync(hookPath,'utf8'),originalHook);
  assert.match(fs.readFileSync(path.join(directory,'AGENTS.md'),'utf8'),/AGENT_PROMPT_V1/);
  await apply({hookIds:[hook.id]});
  assert.match(fs.readFileSync(hookPath,'utf8'),/hook-v2/);
  await apply({removeAssets:[{type:'agent',id:agent.id}]});
  assert.equal((await status()).assets.some(ref=>ref.type==='prompt'),false);
  assert.equal((await status()).assets.some(ref=>ref.type==='hookgroup'),false);
  assert.ok(fs.existsSync(hookPath),'独立更新过的 Hook 保留');
  await apply({removeAssets:[{type:'hook',id:hook.id}]});
  assert.equal(fs.existsSync(hookPath),false);
  // 同一框架切换本次模型时，未操作的配置不被其他 profile 替换。
  const otherModel=await api('model','POST',{message:'创建第二模型',asset:{title:'第二模型',model:'other',baseUrl:'https://example.com'}});
  let profiled=await api('skill','POST',{message:'创建第一配置',asset:{title:'多模型能力',assetHarness:'codex',assetModelId:model.id,variants:{common:{frontmatter:{name:'profiled',description:'测试配置隔离'},body:'MODEL_ONE'}},files:{}}});
  await apply({skillIds:[profiled.id]});
  profiled=await api('skill','POST',{message:'创建第二配置',asset:{...profiled,assetHarness:'codex',assetModelId:otherModel.id,variants:{common:{frontmatter:{name:'profiled',description:'测试配置隔离'},body:'MODEL_TWO'}},files:{}}});
  await apply({modelId:otherModel.id,skillIds:[c.id]});
  assert.match(fs.readFileSync(file('profiled'),'utf8'),/MODEL_ONE/);
  await apply({modelId:otherModel.id,skillIds:[profiled.id]});
  assert.match(fs.readFileSync(file('profiled'),'utf8'),/MODEL_TWO/);
});
