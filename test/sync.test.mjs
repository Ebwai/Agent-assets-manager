import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';

test('两台机器同步、路径本机化、选用旧版后只提交新版本', async t => {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-sync-test-'));
  const remote = path.join(base, 'remote.git');
  const a = path.join(base, 'machine-a'), b = path.join(base, 'machine-b');
  const projectDir = path.join(base, 'project-a');
  fs.mkdirSync(projectDir);
  const run = (cwd, ...args) => {
    const result = spawnSync('git', args, { cwd, encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  };
  fs.mkdirSync(remote);
  run(remote, 'init', '--bare');
  const servers = [];
  t.after(() => { for (const server of servers) server.kill(); fs.rmSync(base, { recursive: true, force: true }); });
  const start = async (dataDir, port) => {
    const server = spawn(process.execPath, ['server.mjs'], { cwd: path.resolve('.'), env: { ...process.env, ASSET_DATA_DIR: dataDir, PORT: String(port) }, stdio: 'pipe' });
    servers.push(server);
    const request = async (url, method = 'GET', body) => {
      const response = await fetch(`http://127.0.0.1:${port}/api/${url}`, { method, headers: { 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
      const value = await response.json();
      if (!response.ok) throw new Error(value.error);
      return value;
    };
    let ready = false;
    for (let i = 0; i < 60; i++) { try { await request('bootstrap'); ready = true; break; } catch { await new Promise(resolve => setTimeout(resolve, 100)); } }
    assert.ok(ready, 'server started');
    return request;
  };
  const requestA = await start(a, 43000 + Math.floor(Math.random() * 1000));
  const project = await requestA('project', 'POST', { message: '创建项目', asset: { title: '演示项目', directory: projectDir, suiteIds: [] } });
  assert.equal(project.directory, projectDir);
  assert.equal(JSON.parse(fs.readFileSync(path.join(a, 'repo/assets/project', `${project.id}.json`), 'utf8')).directory, undefined);
  const baseSkill = { title: '示例 Skill', variants: { common: { frontmatter: { name: 'sample-skill', description: '初始说明' }, body: '## Purpose\n初始正文' } }, files: {} };
  const skill = await requestA('skill', 'POST', { message: '创建初版', asset: baseSkill });
  skill.variants.common.body = '## Purpose\n第二版正文';
  await requestA('skill', 'POST', { message: '创建第二版', asset: skill });
  const firstHash = (await requestA(`skill/${skill.id}/history`))[1].hash;
  run(path.join(a, 'repo'), 'branch', '-M', 'main');
  run(path.join(a, 'repo'), 'remote', 'add', 'origin', remote);
  await requestA('sync/run', 'POST', {});
  assert.equal(run(path.join(a, 'repo'), 'rev-parse', 'HEAD'), run(remote, 'rev-parse', 'refs/heads/main'));
  run(remote, 'symbolic-ref', 'HEAD', 'refs/heads/main');
  fs.mkdirSync(b);
  run(b, 'clone', remote, 'repo');
  fs.mkdirSync(path.join(b, 'private'));
  fs.writeFileSync(path.join(b, 'private/sync.json'), JSON.stringify({ branch: 'main' }));
  const requestB = await start(b, 44000 + Math.floor(Math.random() * 1000));
  const bootstrapB = await requestB('bootstrap');
  assert.equal(bootstrapB.assets.project[0].directory, '');
  assert.equal(bootstrapB.assets.project[0].pathAssigned, false);
  await requestB(`skill/${skill.id}/select-version`, 'POST', { hash: firstHash });
  const selected = await requestB(`skill/${skill.id}`);
  assert.equal(selected.activeVersion, firstHash);
  assert.match(selected.variants.common.body, /初始正文/);
  const previousHead = run(path.join(b, 'repo'), 'rev-parse', 'HEAD');
  selected.variants.common.body = '## Purpose\n从初版改出的第三版';
  await requestB('skill', 'POST', { message: '基于初版改进', asset: selected });
  const latestHead = run(path.join(b, 'repo'), 'rev-parse', 'HEAD');
  assert.equal(run(path.join(b, 'repo'), 'rev-parse', 'HEAD^'), previousHead);
  assert.notEqual(latestHead, firstHash);
  assert.equal((await requestB(`skill/${skill.id}/history`)).length, 3);
  await requestB('sync/run', 'POST', {});
  await requestA('sync/run', 'POST', {});
  assert.match((await requestA(`skill/${skill.id}`)).variants.common.body, /从初版改出的第三版/);
  const localEdit = await requestA(`skill/${skill.id}`);
  localEdit.variants.common.body = '## Purpose\n本机冲突内容';
  await requestA('skill', 'POST', { message: '本机修改', asset: localEdit });
  const remoteEdit = await requestB(`skill/${skill.id}`);
  remoteEdit.variants.common.body = '## Purpose\n远程冲突内容';
  await requestB('skill', 'POST', { message: '远程修改', asset: remoteEdit });
  await requestB('sync/run', 'POST', {});
  const conflict = await requestA('sync/run', 'POST', {});
  assert.equal(conflict.conflicts.length, 1);
  assert.equal(conflict.conflicts[0].type, 'skill');
  await requestA('sync/resolve', 'POST', { choices: { [conflict.conflicts[0].path]: 'local' } });
  assert.match((await requestA(`skill/${skill.id}`)).variants.common.body, /本机冲突内容/);
  assert.equal(run(path.join(a, 'repo'), 'rev-parse', 'HEAD'), run(remote, 'rev-parse', 'refs/heads/main'));
});
