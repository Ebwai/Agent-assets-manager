import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';

test('项目资产扫描只读取；逐项确认、跳过继续、来源变化和去重',async t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'asset-discovery-')),directory=path.join(temp,'project');
  const put=(name,text)=>{const file=path.join(directory,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);};
  put('.claude/rules/api.md','---\npaths: [src/**]\n---\n检查输入');
  put('.claude/rules/broken.md','---\npaths: [\n---\n错误规则');
  put('CLAUDE.md','项目指令\n<!-- Agent Asset Manager: start -->\n已管理指令\n<!-- Agent Asset Manager: end -->');
  put('AGENTS.md','Codex 项目指令');
  put('.claude/skills/check/SKILL.md','---\nname: check\ndescription: 检查内容\n---\n执行检查');
  put('.claude/skills/check/scripts/check.mjs','throw Error("DO NOT EXECUTE");');
  put('.claude/skills/check/assets/sample.bin',Buffer.from([0,255,23]));
  put('.claude/skills/managed/.agent-asset-id','already-managed');
  put('.claude/skills/managed/SKILL.md','---\nname: managed\ndescription: managed\n---\nmanaged');
  put('.claude/agents/review.md','---\nname: review\ndescription: 审查\ntools: Read, Grep\nmodel: sonnet\n---\n审查项目');
  const owned={type:'command',command:'managed hook',timeout:60};
  put('.agent-asset-manager/claude.json',JSON.stringify({hooks:{Stop:[{hooks:[owned]}]}}));
  put('.claude/settings.json',JSON.stringify({hooks:{Stop:[{hooks:[{type:'command',command:'echo test',timeout:5}]},{hooks:[{type:'prompt',prompt:'review'}]},{hooks:[owned]}]}}));
  put('.claude/rules/managed/.agent-asset-id','managed');put('.claude/rules/managed/rule.md','managed');
  const port=47000+Math.floor(Math.random()*10000),data=path.join(temp,'data');
  const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,ASSET_DATA_DIR:data,PORT:String(port)},stdio:'pipe'});
  t.after(()=>{child.kill();fs.rmSync(temp,{recursive:true,force:true});});
  const request=async(url,method='GET',body)=>{const response=await fetch(`http://127.0.0.1:${port}/api/${url}`,{method,headers:{'content-type':'application/json'},body:body?JSON.stringify(body):undefined});const result=await response.json();if(!response.ok)throw Error(result.error);return result;};
  for(let i=0;i<80;i++){try{await request('bootstrap');break;}catch{await new Promise(r=>setTimeout(r,100));}}
  const project=await request('project','POST',{asset:{title:'扫描项目',directory},message:'创建扫描项目'});
  const fileImport=await request('import-hooks','POST',{harness:'codex',fileName:'config.toml',content:'[[hooks.SessionStart]]\n[[hooks.SessionStart.hooks]]\ntype = "command"\ncommand = "echo api"\n'});
  assert.equal(fileImport.candidates[0].asset.event,'SessionStart');
  assert.equal((await request('hook')).length,0,'configuration parsing does not save Hooks');
  const scan=()=>request(`project-discovery?projectId=${project.id}`);
  let result=await scan();assert.equal(result.candidates.length,8);
  assert.deepEqual(new Set(result.candidates.map(c=>c.type)),new Set(['skill','prompt','agent','rule','hook']));
  assert.equal((await request('rule')).length,0,'scan does not save');
  const skill=result.candidates.find(c=>c.type==='skill');assert.equal(skill.asset.files['assets/sample.bin'].encoding,'base64');
  const prompt=result.candidates.find(c=>c.source==='CLAUDE.md');assert.equal(prompt.asset.content,'项目指令');
  assert.equal(result.candidates.filter(c=>!c.importable).length,2);
  const confirm=(item,action='import',extra={})=>request('project-import','POST',{projectId:project.id,key:item.key,fingerprint:item.fingerprint,action,message:'确认项目导入',...extra});
  const rule=result.candidates.find(c=>c.source==='.claude/rules/api.md');
  await confirm(rule);assert.equal((await request('rule')).length,1);assert.equal((await scan()).imported,1);
  await assert.rejects(confirm(rule),/来源内容已变化|已经导入/);
  await confirm(skill,'skip');assert.ok(!(await scan()).candidates.some(c=>c.key===skill.key));
  const retry=await request(`project-discovery?projectId=${project.id}&includeSkipped=true`);assert.equal(retry.candidates.find(c=>c.key===skill.key).decision,'skipped');
  await confirm(skill);const savedSkill=(await request('skill'))[0];assert.equal(savedSkill.files['scripts/check.mjs'],'throw Error("DO NOT EXECUTE");');
  await assert.rejects(confirm(result.candidates.find(c=>!c.importable)),/YAML|command/);
  put('CLAUDE.md','指令已经变化');await assert.rejects(confirm(prompt),/来源内容已变化/);
  result=await scan();await confirm(result.candidates.find(c=>c.source==='CLAUDE.md'));
  await confirm(result.candidates.find(c=>c.type==='agent'));await confirm(result.candidates.find(c=>c.type==='hook'&&c.importable));
  assert.equal((await request('hook')).length,1);
  assert.equal(fs.readFileSync(path.join(directory,'CLAUDE.md'),'utf8'),'指令已经变化');
  assert.equal(fs.readFileSync(path.join(directory,'.claude/rules/api.md'),'utf8'),'---\npaths: [src/**]\n---\n检查输入');
  assert.ok(fs.existsSync(path.join(data,'private/project-imports.json')));
  assert.ok(!fs.existsSync(path.join(data,'repo/project-imports.json')));
  put('.claude/rules/api.md','修改后的规则');assert.ok((await scan()).candidates.some(c=>c.source==='.claude/rules/api.md'));
  const changedRule=(await scan()).candidates.find(c=>c.source==='.claude/rules/api.md');
  await assert.rejects(confirm(changedRule),/同名资产/);
  assert.equal((await request('rule')).length,1,'duplicate name does not create another asset');
  assert.equal((await request('rule'))[0].content,'检查输入','existing asset remains unchanged');
  await confirm(changedRule,'import',{title:'api-修改版'});
  assert.equal((await request('rule')).length,2,'renaming permits import');
  const outside=path.join(temp,'outside');fs.mkdirSync(outside);fs.writeFileSync(path.join(outside,'secret.md'),'outside secret');
  fs.symlinkSync(outside,path.join(directory,'.claude/rules/linked'),process.platform==='win32'?'junction':'dir');
  result=await scan();assert.ok(result.warnings.some(w=>w.includes('linked')));assert.ok(!JSON.stringify(result).includes('outside secret'));
});
